package com.nci.fogedge.security;

/**
 * Enum representing different types of security attacks in the simulation.
 */
public enum AttackType {
    /**
     * Distributed Denial of Service attack
     */
    DDOS,
    
    /**
     * Data breach attack
     */
    DATA_BREACH,
    
    /**
     * Man-in-the-middle attack
     */
    MAN_IN_THE_MIDDLE,
    
    /**
     * Malware attack
     */
    MALWARE,
    
    /**
     * Ransomware attack
     */
    RANSOMWARE
}
